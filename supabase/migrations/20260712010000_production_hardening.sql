-- Production hardening: ownership, atomic quota + graph creation, RAG and billing state.
create extension if not exists vector with schema extensions;

create table if not exists public.document_chunks (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profile(id) on delete cascade,
  study_bot_id bigint not null references public.study_bots(id) on delete cascade,
  document_id bigint references public.study_bot_documents(id) on delete cascade,
  document_name text not null check (char_length(document_name) between 1 and 255),
  content text not null check (char_length(content) > 0),
  chunk_index integer not null check (chunk_index >= 0),
  mime_type text,
  source_type text not null default 'text',
  source_locator text,
  embedding extensions.vector(384),
  fts tsvector generated always as (to_tsvector('english', coalesce(content, ''))) stored,
  created_at timestamptz not null default now(),
  unique (document_id, chunk_index)
);
-- Brownfield: earlier migration created document_chunks without source_locator.
alter table public.document_chunks add column if not exists source_locator text;
alter table public.document_chunks enable row level security;
drop policy if exists document_chunks_select_own on public.document_chunks;
create policy document_chunks_select_own on public.document_chunks for select to authenticated using (profile_id = (select auth.uid()));
drop policy if exists document_chunks_insert_own on public.document_chunks;
create policy document_chunks_insert_own on public.document_chunks for insert to authenticated with check (profile_id = (select auth.uid()) and exists (select 1 from public.study_bots b where b.id = study_bot_id and b.profile_id = (select auth.uid())));
drop policy if exists document_chunks_delete_own on public.document_chunks;
create policy document_chunks_delete_own on public.document_chunks for delete to authenticated using (profile_id = (select auth.uid()));
create index if not exists document_chunks_owner_bot_idx on public.document_chunks(profile_id, study_bot_id, chunk_index);
create index if not exists document_chunks_fts_idx on public.document_chunks using gin(fts);

